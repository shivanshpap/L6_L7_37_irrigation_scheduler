# 2. Hypothesis Fuzz Tests for water_volume()
# =====================================================================

@given(area_m2=fuzz_scalars, stage=fuzz_scalars, temp_c=fuzz_scalars)
@settings(max_examples=200)
def test_fuzz_water_volume_safety(area_m2, stage, temp_c):
    """
    SAFETY INVARIANT: water_volume must never crash unexpectedly or produce NaN/Inf.
    It must either return a strictly positive finite float or raise (ValueError, TypeError).
    """
    try:
        vol = water_volume(area_m2, stage, temp_c)
        assert isinstance(vol, float)
        assert math.isfinite(vol)
        assert vol > 0.0
    except (ValueError, TypeError):
        pass


@given(area=valid_areas, stage=valid_stages, temp=valid_temps)
@settings(max_examples=100)
def test_water_volume_proportionality(area, stage, temp):
    """
    PROPERTY: Doubling the zone area must double the calculated water volume.
    """
    vol1 = water_volume(area, stage, temp)
    vol2 = water_volume(area * 2.0, stage, temp)
    assert math.isclose(vol2, vol1 * 2.0, rel_tol=1e-5)


