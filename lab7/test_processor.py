def test_should_irrigate_happy_path():
    assert should_irrigate(40.0, 0.0, "seedling") is True
    assert should_irrigate(50.0, 0.0, "seedling") is False
    assert should_irrigate(50.0, 0.0, "flowering") is True
    assert should_irrigate(58.0, 0.0, "flowering") is False
    assert should_irrigate(35.0, 2.0, "vegetative") is True
    assert should_irrigate(35.0, 6.0, "vegetative") is False
    assert should_irrigate(70.0, 0.0, "seedling") is False
    assert should_irrigate(30.0, 15.0, "seedling") is False


def test_should_irrigate_edge_case_rejections():
    # Moisture bounds and types
    with pytest.raises(ValueError):
        should_irrigate(-5.0, 0.0, "seedling")
    with pytest.raises(ValueError):
        should_irrigate(105.0, 0.0, "seedling")
    with pytest.raises(ValueError):
        should_irrigate(float('nan'), 0.0, "seedling")
    with pytest.raises(ValueError):
        should_irrigate(float('inf'), 0.0, "seedling")
    with pytest.raises(TypeError):
        should_irrigate(None, 0.0, "seedling")
    with pytest.raises(TypeError):
        should_irrigate(True, 0.0, "seedling")  # Booleans rejected
    with pytest.raises(TypeError):
        should_irrigate("dry", 0.0, "seedling")

    # Rain bounds and types
    with pytest.raises(ValueError):
        should_irrigate(30.0, -1.0, "seedling")
    with pytest.raises(TypeError):
        should_irrigate(30.0, None, "seedling")

    # Stage validation
    with pytest.raises(ValueError):
        should_irrigate(30.0, 0.0, "invalid_stage")
    with pytest.raises(ValueError):
        should_irrigate(30.0, 0.0, "   ")
    with pytest.raises(TypeError):
        should_irrigate(30.0, 0.0, 123)
    with pytest.raises(TypeError):
        should_irrigate(30.0, 0.0, None)


def test_water_volume_happy_path():
    # Seedling base: 2 L/m2
    assert water_volume(10.0, "seedling", 20.0) == 20.0
    # Flowering base: 5 L/m2
    assert water_volume(10.0, "flowering", 20.0) == 50.0
    # Vegetative base: 4 L/m2
    assert water_volume(10.0, "vegetative", 20.0) == 40.0
    # Hot boost (>35 C): 1.5x
    assert water_volume(10.0, "seedling", 36.0) == 30.0
    # Cold reduction (<10 C): 0.5x
    assert water_volume(10.0, "seedling", 8.0) == 10.0


def test_water_volume_edge_case_rejections():
    # Area edge cases
    with pytest.raises(ValueError):
        water_volume(0.0, "seedling", 20.0)
    with pytest.raises(ValueError):
        water_volume(-10.0, "seedling", 20.0)
    with pytest.raises(ValueError):
        water_volume(float('nan'), "seedling", 20.0)
    with pytest.raises(TypeError):
        water_volume(None, "seedling", 20.0)
    with pytest.raises(TypeError):
        water_volume(True, "seedling", 20.0)

    # Temperature bounds
    with pytest.raises(ValueError):
        water_volume(10.0, "seedling", 100.0)  # > 60 C
    with pytest.raises(ValueError):
        water_volume(10.0, "seedling", -60.0)  # < -50 C
    with pytest.raises(ValueError):
        water_volume(10.0, "seedling", float('nan'))
    with pytest.raises(TypeError):
        water_volume(10.0, "seedling", "hot")

    # Stage invalidation
    with pytest.raises(ValueError):
        water_volume(10.0, "unknown_crop", 20.0)
    with pytest.raises(TypeError):
        water_volume(10.0, None, 20.0)


def test_schedule_happy_path():
    zones = [
        ("Z1", 100.0, 30.0, 0.0, "seedling", 20.0),   # Needs 200 L
        ("Z2", 200.0, 50.0, 0.0, "flowering", 20.0),  # Needs 1000 L
        ("Z3", 100.0, 70.0, 0.0, "seedling", 20.0),   # Moisture 70 -> No irrigation
    ]
    # Budget 500 covers only Z1
    assert schedule(zones, 500.0) == ["Z1"]
    # Budget 1500 covers Z1 and Z2
    assert schedule(zones, 1500.0) == ["Z1", "Z2"]
    # Empty zones list
    assert schedule([], 1000.0) == []


def test_schedule_edge_case_rejections():
    # Zones container validation
    with pytest.raises(TypeError):
        schedule(None, 1000.0)
    with pytest.raises(TypeError):
        schedule(12345, 1000.0)
    with pytest.raises(TypeError):
        schedule("invalid_zones_string", 1000.0)

    # Budget validation
    with pytest.raises(ValueError):
        schedule([], -50.0)
    with pytest.raises(ValueError):
        schedule([], float('nan'))
    with pytest.raises(TypeError):
        schedule([], None)
    with pytest.raises(TypeError):
        schedule([], "infinite_budget")

    # Malformed zone item
    with pytest.raises(ValueError):
        schedule([("Z1", 100.0)], 1000.0)  # wrong length (2 instead of 6)
    with pytest.raises(TypeError):
        schedule(["not_a_tuple"], 1000.0)
    with pytest.raises(ValueError):
        schedule([("", 100.0, 30.0, 0.0, "seedling", 20.0)], 1000.0)  # empty name
