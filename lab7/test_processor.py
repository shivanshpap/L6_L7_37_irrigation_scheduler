import math
import pytest
from hypothesis import given, settings, strategies as st

# Import hardened functions from processor.py (or irrigation_scheduler.py)
from processor import should_irrigate, water_volume, schedule, VALID_STAGES


# =====================================================================
# Hypothesis Strategies
# =====================================================================

# Comprehensive fuzz strategy generating varied scalar data types
fuzz_scalars = st.one_of(
    st.none(),
    st.booleans(),
    st.integers(min_value=-1000, max_value=1000),
    st.floats(allow_nan=True, allow_infinity=True, width=32),
    st.text(max_size=25),
)

# Valid strategies for generating legitimate data
valid_moistures = st.floats(min_value=0.0, max_value=100.0, allow_nan=False, allow_infinity=False)
valid_rains = st.floats(min_value=0.0, max_value=200.0, allow_nan=False, allow_infinity=False)
valid_stages = st.sampled_from(list(VALID_STAGES))
valid_areas = st.floats(min_value=0.1, max_value=10000.0, allow_nan=False, allow_infinity=False)
valid_temps = st.floats(min_value=-40.0, max_value=55.0, allow_nan=False, allow_infinity=False)
valid_budgets = st.floats(min_value=0.0, max_value=100000.0, allow_nan=False, allow_infinity=False)

# Strategy for valid zone tuples
valid_zone_tuple = st.tuples(
    st.text(alphabet=st.characters(whitelist_categories=('Lu', 'Ll', 'Nd')), min_size=1, max_size=15),
    valid_areas,
    valid_moistures,
    valid_rains,
    valid_stages,
    valid_temps
)


# =====================================================================
# 1. Hypothesis Fuzz Tests for should_irrigate()
# =====================================================================

@given(moisture=fuzz_scalars, rain_mm=fuzz_scalars, stage=fuzz_scalars)
@settings(max_examples=200)
def test_fuzz_should_irrigate_safety(moisture, rain_mm, stage):
    """
    SAFETY INVARIANT: should_irrigate must never crash with unhandled exceptions.
    It must either return a boolean (for valid input) or raise (ValueError, TypeError).
    """
    try:
        result = should_irrigate(moisture, rain_mm, stage)
        assert isinstance(result, bool)
    except (ValueError, TypeError):
        pass


@given(moisture=valid_moistures, rain_mm=valid_rains, stage=valid_stages)
@settings(max_examples=100)
def test_should_irrigate_properties_on_valid_inputs(moisture, rain_mm, stage):
    """
    BEHAVIORAL INVARIANTS:
    1. If moisture >= 60%, never irrigate.
    2. If rain >= 10mm, never irrigate.
    """
    result = should_irrigate(moisture, rain_mm, stage)
    assert isinstance(result, bool)
    if moisture >= 60.0:
        assert result is False
    if rain_mm >= 10.0:
        assert result is False


