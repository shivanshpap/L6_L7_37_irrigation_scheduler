# 3. Hypothesis Fuzz Tests for schedule()
# =====================================================================

# Arbitrary zones structure for fuzzing
fuzz_zones = st.one_of(
    st.none(),
    st.integers(),
    st.text(),
    st.lists(
        st.one_of(
            st.tuples(st.text(), fuzz_scalars, fuzz_scalars, fuzz_scalars, fuzz_scalars, fuzz_scalars),
            st.tuples(st.text()),
            st.none(),
            st.integers(),
        ),
        max_size=10
    )
)

@given(zones=fuzz_zones, budget=fuzz_scalars)
@settings(max_examples=200)
def test_fuzz_schedule_safety(zones, budget):
    """
    SAFETY INVARIANT: schedule must never crash on malformed zone structures,
    None values, or non-numeric budgets. It must raise (ValueError, TypeError) or
    return a valid list of zone name strings.
    """
    try:
        plan = schedule(zones, budget)
        assert isinstance(plan, list)
        assert all(isinstance(name, str) for name in plan)
    except (ValueError, TypeError):
        pass


@given(zones=st.lists(valid_zone_tuple, max_size=15), budget=valid_budgets)
@settings(max_examples=100)
def test_schedule_budget_invariant(zones, budget):
    """
    BUDGET CONSERVATION INVARIANT:
    The sum of water volumes for all scheduled zones must never exceed the budget.
    """
    plan = schedule(zones, budget)
    assert isinstance(plan, list)
    
    total_water_used = 0.0
    zone_dict = {z[0]: z for z in zones}
    for name in plan:
        z = zone_dict[name]
        vol = water_volume(z[1], z[4], z[5])
        total_water_used += vol
        
    assert total_water_used <= budget + 1e-5


